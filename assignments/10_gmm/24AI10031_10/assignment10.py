"""## 2. GMM Implementation from Scratch (4 Marks)

1. Implement the Expectation-Maximization (EM) algorithm for a Gaussian Mixture Model from scratch (1M)
2. Fit this GMM model using only the authentic samples from the training set. (2 M)
3. Plot the log-likelihood vs. iteration to demonstrate convergence. (1 M)
"""

import numpy as np
from scipy.stats import multivariate_normal

class GaussianMixtureModel:
    def __init__(self, n_components=2, max_iters=200, tol=1e-3, random_state=42):
        self.n_components = n_components
        self.max_iters = max_iters
        self.tol = tol
        self.random_state = random_state
        self.log_likelihoods = []

    def fit(self, X):
        np.random.seed(self.random_state)
        N, D = X.shape
        self.pi = np.ones(self.n_components) / self.n_components

        # Initialize means randomly from data points
        indices = np.random.choice(N, self.n_components, replace=False)
        self.mu = X[indices]
        self.sigma = np.array([np.cov(X.T) + 1e-6*np.eye(D) for _ in range(self.n_components)])

        for it in range(self.max_iters):
            # E-step
            r = np.zeros((N, self.n_components))
            for k in range(self.n_components):
                r[:, k] = self.pi[k] * multivariate_normal.pdf(X, mean=self.mu[k], cov=self.sigma[k])

            r_total = np.sum(r, axis=1)
            ll = np.sum(np.log(r_total + 1e-12))
            self.log_likelihoods.append(ll)

            r_sum = r_total[:, None]
            r_sum[r_sum == 0] = 1e-12
            r = r / r_sum

            # M-step
            N_k = r.sum(axis=0)
            self.pi = N_k / N
            self.mu = (r.T @ X) / N_k[:, None]

            for k in range(self.n_components):
                X_centered = X - self.mu[k]
                weighted = (r[:, k][:, None] * X_centered).T @ X_centered
                self.sigma[k] = weighted / N_k[k] + 1e-6 * np.eye(D)

            if it > 0 and abs(self.log_likelihoods[-1] - self.log_likelihoods[-2]) < self.tol:
                print(f"Converged at iteration {it}")
                break

    def score_samples(self, X):
        N = X.shape[0]
        r = np.zeros((N, self.n_components))
        for k in range(self.n_components):
            r[:, k] = self.pi[k] * multivariate_normal.pdf(X, mean=self.mu[k], cov=self.sigma[k])
        return np.log(np.sum(r, axis=1) + 1e-12)

